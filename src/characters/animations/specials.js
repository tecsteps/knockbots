/**
 * Knockbots — special moves and the three-part overdrive.
 *
 * Same rig conventions as punches.js.
 *
 * Specials are allowed to be louder than normals, but they still have to be
 * legible in a single frame. Each one is built around one silhouette the camera
 * can hold on: the rocket punch is a fully locked-out arm with the chassis
 * recoiling backwards away from it, the shoulder charge is a head-below-the-
 * shoulders drive that eats a metre and a half of ground, and the overdrive is
 * three separate clips so the combat system can hold the cinematic between
 * them.
 *
 *   sp.overdriveStart   ignition: plant, flare, and a long settle on the peak
 *                       pose while the camera swings around.
 *   sp.overdriveHit     the connecting blow: a blind-fast lunge into a rising
 *                       two-handed strike that carries through its contact.
 *   sp.overdriveFinish  the finisher: a full turn, then both fists buried in the
 *                       ground, easing into a hero silhouette.
 *
 * Those long beats are settles, never freezes: the pose keeps drifting a couple
 * of degrees through them. A held frame at 60Hz reads as a stall in the engine,
 * not as a fighter holding still.
 *
 * Each clip a move strikes with declares `impact: { tick, bone }` — the tick the
 * blow lands and the bone it lands with — which is what Fighter pins onto the
 * move's first active frame. Move the strike and the declaration moves with it.
 *
 * sp.counterStance loops so the combat system can hold the counter window open
 * for as long as the move's parry frames last.
 */

