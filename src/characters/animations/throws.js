/**
 * Knockbots — throws, including the paired thrower/victim animations.
 *
 * Same rig conventions as punches.js.
 *
 * PAIRING CONTRACT — t.throwForward (thrower) and t.beingThrown (victim) are
 * authored as one shot and only work together. While they play, the combat
 * system must park the victim relative to the thrower:
 *
 *   victim.root.position = thrower.position + thrower.forward * 0.78
 *   victim.root.rotation.y = thrower.rotation.y + PI      // facing the thrower
 *
 * and then let each clip's own root track do the rest. Because the victim is
 * turned to face the thrower, +Z in t.beingThrown's root keys points BACK at the
 * thrower. Beat for beat:
 *
 *   tick  0- 8   contact; the victim is still on its feet
 *   tick  8-14   the thrower's hands pass the victim's chest and lift
 *   tick 14-22   the victim leaves the floor, hips rising to ~1.5 m world
 *   tick 22-26   inverted at the apex, legs trailing overhead
 *   tick 26-30   driven down; the back lands on tick 30 — this is the frame the
 *                combat system should emit 'groundImpact' and the camera shake
 *   tick 30-54   settle. The victim comes to rest lying on its back with its
 *                head 1.4 m from the thrower and its feet just short of the
 *                thrower's own, then hands off to r.knockdownBack.
 *
 * t.throwBack (suplex) reuses t.beingThrown; place the victim the same way and
 * the arch carries them over the thrower's shoulder to land behind. t.beingGrabbed
 * loops, so a hold can last exactly as long as the throw-break window.
 */

